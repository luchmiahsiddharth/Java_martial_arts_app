    public RatingsForm() {
        initComponents();
        setExtendedState(MAXIMIZED_BOTH);
        getContentPane().setBackground(new java.awt.Color(20,20,25));        
        setLocationRelativeTo(null);
        
        //populating the table
        DefaultTableModel model =(DefaultTableModel) RatingsTable.getModel();
        try (Reader ratingsReader = new InputStreamReader(new FileInputStream("Ratings.txt"), StandardCharsets.UTF_8)) {
            try (Reader classReader = new InputStreamReader(new FileInputStream("Martial_Classes.txt"), StandardCharsets.UTF_8)) {
                
                           
            JsonArray ratingRecords = JsonParser.parseReader(ratingsReader).getAsJsonArray();
            JsonArray classRecords = JsonParser.parseReader(classReader).getAsJsonArray();
            
            for (JsonElement ratingElement : ratingRecords) {
                JsonObject ratingRecord = ratingElement.getAsJsonObject();
                   
                    if (currentInstructor.taughtClasses().contains(ratingRecord.get("classId").getAsString())){
                        for (JsonElement classElement : classRecords) {
                            JsonObject classRecord = classElement.getAsJsonObject();
                            if (ratingRecord.get("classId").getAsString().equals(classRecord.get("classId").getAsString())){
                                className=classRecord.get("className").getAsString();
                            }   
                           
                        }    
                            
                         model.addRow(new Object[]{
                            ratingRecord.get("classId").getAsString(),
                            className,
                            ratingRecord.get("rating").getAsString(),
                            ratingRecord.get("studentFirstName").getAsString()
                        });                       
                    }else{
                        
                    }

                
            }
                
            }catch(IOException e){
            JOptionPane.showMessageDialog(null, e.getMessage());
            }   
         
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, e.getMessage());
        }        
        
        //search bar
        
        searchtxt.setText("Search...");
        searchtxt.setForeground(java.awt.Color.GRAY);

    }

